#!/bin/bash

# Medical Dashboard Inter Font Downloader
# Downloads Inter font files for self-hosting

set -e

# Configuration
FONT_DIR="public/fonts/inter"
TEMP_DIR="/tmp/inter-fonts"
INTER_VERSION="4.0"

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

echo -e "${BLUE}🔤 Medical Dashboard Font Downloader${NC}"
echo -e "${BLUE}Downloading Inter font files for self-hosting...${NC}\n"

# Create directories
echo -e "${YELLOW}📁 Creating font directories...${NC}"
mkdir -p "$FONT_DIR"
mkdir -p "$TEMP_DIR"

# Download Inter font files from official repository
echo -e "${YELLOW}⬇️  Downloading Inter font files...${NC}"

# Inter font files URLs (official repository)
FONT_FILES=(
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Light.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Light.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Regular.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Regular.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Medium.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Medium.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-SemiBold.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-SemiBold.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Bold.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Bold.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-ExtraBold.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-ExtraBold.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Black.woff2"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Black.woff"
    "https://github.com/rsms/inter/raw/master/docs/font-files/Inter-Variable.woff2"
)

# Download each font file
for url in "${FONT_FILES[@]}"; do
    filename=$(basename "$url")
    echo -e "  ⬇️  Downloading ${filename}..."
    
    if command -v curl >/dev/null 2>&1; then
        curl -L -o "$TEMP_DIR/$filename" "$url" --silent --show-error
    elif command -v wget >/dev/null 2>&1; then
        wget -q -O "$TEMP_DIR/$filename" "$url"
    else
        echo -e "${RED}❌ Error: Neither curl nor wget found. Please install one of them.${NC}"
        exit 1
    fi
    
    # Check if download was successful
    if [ -f "$TEMP_DIR/$filename" ] && [ -s "$TEMP_DIR/$filename" ]; then
        echo -e "${GREEN}  ✅ Downloaded ${filename}${NC}"
    else
        echo -e "${RED}  ❌ Failed to download ${filename}${NC}"
        exit 1
    fi
done

# Move files to destination
echo -e "\n${YELLOW}📦 Installing font files...${NC}"
cp "$TEMP_DIR"/* "$FONT_DIR/"

# Verify installation
echo -e "\n${YELLOW}🔍 Verifying installation...${NC}"
for file in "$FONT_DIR"/*.woff2; do
    if [ -f "$file" ]; then
        size=$(du -h "$file" | cut -f1)
        echo -e "${GREEN}  ✅ $(basename "$file") (${size})${NC}"
    fi
done

# Generate CSS file with correct paths
echo -e "\n${YELLOW}📝 Generating CSS reference...${NC}"
cat > "$FONT_DIR/inter-reference.css" << 'EOF'
/**
 * Self-hosted Inter Font Files
 * Generated by download-inter-fonts.sh
 */

/* Critical font weights for immediate loading */
@font-face {
  font-family: 'Inter';
  src: url('./Inter-Regular.woff2') format('woff2'),
       url('./Inter-Regular.woff') format('woff');
  font-weight: 400;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'Inter';
  src: url('./Inter-Medium.woff2') format('woff2'),
       url('./Inter-Medium.woff') format('woff');
  font-weight: 500;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'Inter';
  src: url('./Inter-SemiBold.woff2') format('woff2'),
       url('./Inter-SemiBold.woff') format('woff');
  font-weight: 600;
  font-style: normal;
  font-display: swap;
}

/* Additional font weights */
@font-face {
  font-family: 'Inter';
  src: url('./Inter-Light.woff2') format('woff2'),
       url('./Inter-Light.woff') format('woff');
  font-weight: 300;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'Inter';
  src: url('./Inter-Bold.woff2') format('woff2'),
       url('./Inter-Bold.woff') format('woff');
  font-weight: 700;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'Inter';
  src: url('./Inter-ExtraBold.woff2') format('woff2'),
       url('./Inter-ExtraBold.woff') format('woff');
  font-weight: 800;
  font-style: normal;
  font-display: swap;
}

@font-face {
  font-family: 'Inter';
  src: url('./Inter-Black.woff2') format('woff2'),
       url('./Inter-Black.woff') format('woff');
  font-weight: 900;
  font-style: normal;
  font-display: swap;
}

/* Variable font for modern browsers */
@font-face {
  font-family: 'Inter Variable';
  src: url('./Inter-Variable.woff2') format('woff2-variations');
  font-weight: 100 900;
  font-style: normal;
  font-display: swap;
}
EOF

echo -e "${GREEN}  ✅ Generated inter-reference.css${NC}"

# Cleanup
echo -e "\n${YELLOW}🧹 Cleaning up...${NC}"
rm -rf "$TEMP_DIR"

# Calculate total size
total_size=$(du -sh "$FONT_DIR" | cut -f1)

echo -e "\n${GREEN}🎉 Font installation complete!${NC}"
echo -e "${GREEN}📊 Total size: ${total_size}${NC}"
echo -e "${GREEN}📁 Location: ${FONT_DIR}${NC}"
echo -e "\n${BLUE}Next steps:${NC}"
echo -e "1. Update your CSS files to use the self-hosted fonts"
echo -e "2. Remove Google Fonts references from HTML templates"
echo -e "3. Test font loading in your application"
echo -e "4. Consider setting up font preloading for better performance"

echo -e "\n${YELLOW}💡 Performance tips:${NC}"
echo -e "• Use font-display: swap for better loading experience"
echo -e "• Preload critical font weights (400, 500, 600)"
echo -e "• Consider using the variable font for modern browsers"
echo -e "• Test on slow connections to ensure good fallback behavior"